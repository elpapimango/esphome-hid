#!/usr/bin/env python3
"""Writes components/hid_streamdeck/xl_data.h from a dump of a real Stream Deck XL
(streamdeck-xl-mimic/tools/dump_streamdeck.py): the 211-byte HID report descriptor and the replies to every feature report.

    python tools/gen_streamdeck_xl_data.py ../streamdeck-xl-mimic/captures-linux/xl-006c-dump.json > components/hid_streamdeck/xl_data.h
"""
import json
import sys

dump = json.load(open(sys.argv[1], encoding="utf-8"))
desc = bytes.fromhex(dump["report_descriptor_hex"])
assert len(desc) == dump["report_descriptor_bytes"] == 211


def rows(data, indent="    "):
    return "\n".join(indent + ", ".join(f"0x{b:02X}" for b in data[i : i + 12]) + "," for i in range(0, len(data), 12))


print("// Generated by tools/gen_streamdeck_xl_data.py from a read-only dump of a real Stream Deck XL (0FD9:006C, firmware 1.01.000).")
print("// Do not edit by hand. The serial number (feature 0x06) is not replayed: the component uses its own.")
print("#pragma once\n#include <stdint.h>\n\nnamespace esphome {\nnamespace hid_streamdeck {\n")
print(f"// HID report descriptor, {len(desc)} bytes: input report 1 (511 bytes), output report 2 (1023 bytes), feature reports 3 to 12 (31 bytes).")
print(f"static const uint8_t XL_REPORT_DESCRIPTOR[{len(desc)}] = {{\n{rows(desc)}\n}};\n")
print("// What the real XL answers to GET_REPORT of each feature report (payload after the report id, 31 bytes).")
print("struct FeatureReply { uint8_t id; uint8_t payload[31]; };")
print("static const FeatureReply XL_FEATURE_REPLIES[] = {")
for key, value in sorted(dump["feature_reports"].items()):
    data = bytes.fromhex(value["hex"])
    rid, payload = data[0], data[1:]
    assert len(payload) == 31, (key, len(payload))
    if rid == 0x06:
        continue  # the serial number
    print("    {0x%02X, {%s}}," % (rid, ", ".join(f"0x{b:02X}" for b in payload)))
print("};\n\n}  // namespace hid_streamdeck\n}  // namespace esphome")
